/**
 * Returns the list of all 36 authoritative Indian states and UTs.
 */
export function getAuthoritativeStates(): string[] {
  return [...AUTHORITATIVE_INDIAN_STATES_AND_UTS];
}

/**
 * Returns genuine districts for a specific state, or an empty array if nationwide.
 */
export function getDistrictsForState(stateName?: string | null): string[] {
  if (!stateName || isAllStates(stateName)) {
    return [];
  }
  const normalized = stateName.trim();
  // Find case-insensitive match
  const match = Object.keys(STATE_DISTRICT_MAP).find(
    (k) => k.toLowerCase() === normalized.toLowerCase()
  );
  return match ? [...STATE_DISTRICT_MAP[match]].sort() : [];
}

/**
 * Checks if a state string represents the "All States" selection.
 */
export function isAllStates(state?: string | null): boolean {
  if (!state) return true;
  const s = state.trim().toLowerCase();
  return (
    s === "" ||
    s === "all" ||
    s === "all states" ||
    s === "all states / uts (nationwide)" ||
    s === "all states / uts" ||
    s === "nationwide"
  );
}

/**
 * Checks if a district string represents the "All Districts" selection.
 */
export function isAllDistricts(district?: string | null): boolean {
  if (!district) return true;
  const d = district.trim().toLowerCase();
  return (
    d === "" ||
    d === "all" ||
    d === "all districts" ||
    d === "all mandis" ||
    d === "all markets"
  );
}
