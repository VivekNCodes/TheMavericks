export function getReferenceRecords(): NormalizedMandiRecord[] {
  const now = new Date();

  return SEED_DATA.map((item) => {
    const arrivalDate = new Date(item.recordDate);
    const diffTime = Math.abs(now.getTime() - arrivalDate.getTime());
    const daysAgo = Math.floor(diffTime / (1000 * 60 * 60 * 24));

    const recordHash = generateRecordHash({
      state: item.state,
      district: item.district,
      mandiName: item.mandiName,
      cropName: item.cropName,
      variety: item.variety,
      grade: item.grade,
      recordDate: arrivalDate,
    });

    return {
      state: item.state,
      district: item.district,
      mandiName: item.mandiName,
      cropName: item.cropName,
      variety: item.variety,
      grade: item.grade,
      minPrice: item.minPrice,
      modalPrice: item.modalPrice,
      maxPrice: item.maxPrice,
      priceUnit: item.priceUnit,
      arrivalsTonnes: null,
      trendPercent: null,
      source: "Agmarknet (data.gov.in)",
      recordDate: arrivalDate.toISOString(),
      fetchedAt: now.toISOString(),
      recordHash,
      isStale: daysAgo > 2,
      daysAgo,
    };
  });
}

export const REFERENCE_MANDI_RECORDS: NormalizedMandiRecord[] = getReferenceRecords();

